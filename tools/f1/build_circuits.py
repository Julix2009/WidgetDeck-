#!/usr/bin/env python3
"""Builds qml/widgets/f1/circuits.json (the track outlines of the F1 widget) from the MIT-licensed GeoJSON of bacinger/f1-circuits.

    curl -sLo /tmp/f1-circuits.geojson https://raw.githubusercontent.com/bacinger/f1-circuits/master/f1-circuits.geojson
    python3 tools/f1/build_circuits.py /tmp/f1-circuits.geojson

Per circuit: project lon / lat to a local plane (equirectangular, so the shape is not distorted), north up, fit into a 0..1000 box
(the longer side = 1000, aspect ratio kept), round the corners once (Chaikin, keeps the straights straight), simplify (Ramer-Douglas-Peucker)
to a few hundred points and store the points as integers. The widget scales these coordinates to the space it has (no scale transform on any item).
Nothing is downloaded at install time: the finished file is part of the repository. Source licence: see LICENSES/MIT-f1-circuits.txt and NOTICE.md.
"""
import json
import math
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "..", "qml", "widgets", "f1", "circuits.json")


def chaikin(pts, closed):
    out = []
    n = len(pts)
    for i in range(n if closed else n - 1):
        a, b = pts[i], pts[(i + 1) % n]
        out.append((0.75 * a[0] + 0.25 * b[0], 0.75 * a[1] + 0.25 * b[1]))
        out.append((0.25 * a[0] + 0.75 * b[0], 0.25 * a[1] + 0.75 * b[1]))
    return out if closed else [pts[0]] + out[1:-1] + [pts[-1]]


def rdp(pts, eps):
    if len(pts) < 3:
        return pts
    a, b = pts[0], pts[-1]
    dx, dy = b[0] - a[0], b[1] - a[1]
    norm = math.hypot(dx, dy) or 1e-12
    dmax, idx = 0.0, 0
    for i in range(1, len(pts) - 1):
        d = abs(dy * pts[i][0] - dx * pts[i][1] + b[0] * a[1] - b[1] * a[0]) / norm
        if d > dmax:
            dmax, idx = d, i
    if dmax > eps:
        return rdp(pts[: idx + 1], eps)[:-1] + rdp(pts[idx:], eps)
    return [a, b]


def build(feature):
    c = feature["geometry"]["coordinates"]
    lat0 = sum(p[1] for p in c) / len(c)
    k = math.cos(math.radians(lat0))
    pts = [(p[0] * k, -p[1]) for p in c]                      # y down = north up
    closed = math.hypot(pts[0][0] - pts[-1][0], pts[0][1] - pts[-1][1]) < 1e-9
    if closed:
        pts = pts[:-1]
    x0 = min(p[0] for p in pts); x1 = max(p[0] for p in pts); y0 = min(p[1] for p in pts); y1 = max(p[1] for p in pts)
    span = max(x1 - x0, y1 - y0)
    scale = 1000.0 / span
    pts = [((p[0] - x0) * scale, (p[1] - y0) * scale) for p in pts]
    pts = chaikin(pts, closed)
    if closed:                                                  # a closed loop: split at the point farthest from the start so both halves are real chains
        far = max(range(len(pts)), key=lambda i: math.hypot(pts[i][0] - pts[0][0], pts[i][1] - pts[0][1]))
        pts = rdp(pts[: far + 1], 0.9)[:-1] + rdp(pts[far:] + [pts[0]], 0.9)[:-1]
    else:
        pts = rdp(pts, 0.9)
    w, h = (x1 - x0) * scale, (y1 - y0) * scale
    flat = []
    for p in pts:
        flat += [round(p[0]), round(p[1])]
    length = 0.0
    q = pts + ([pts[0]] if closed else [])
    for i in range(len(q) - 1):
        length += math.hypot(q[i + 1][0] - q[i][0], q[i + 1][1] - q[i][1])
    return {"w": round(w), "h": round(h), "closed": closed, "len": round(length), "pts": flat}


def main():
    if len(sys.argv) < 2:
        sys.exit(__doc__)
    gj = json.load(open(sys.argv[1], encoding="utf-8"))
    by = {f["properties"]["id"]: f for f in gj["features"]}
    cmap = {k: v for k, v in json.load(open(os.path.join(HERE, "circuit-map.json"), encoding="utf-8")).items() if not k.startswith("_")}
    out, missing = {}, []
    for cid, gid in cmap.items():
        f = by.get(gid)
        if not f:
            missing.append(cid)
            continue
        p = f["properties"]
        o = build(f)
        o.update({"name": p.get("Name", ""), "length_m": p.get("length"), "source": "bacinger/f1-circuits " + gid})
        out[cid] = o
    with open(OUT, "w", encoding="utf-8") as fh:
        json.dump({"_comment": "Track outlines for the F1 widget, derived from bacinger/f1-circuits (MIT, (c) Tomislav Bacinger) - see NOTICE.md. Unofficial; Formula 1 marks belong to their owners. Built by tools/f1/build_circuits.py.", "circuits": out}, fh, separators=(",", ":"), ensure_ascii=False)
    with open(os.path.join(os.path.dirname(OUT), "circuits.js"), "w", encoding="utf-8") as fh:        # the same data as a QML-loadable library
        fh.write(".pragma library\n// generated by tools/f1/build_circuits.py from circuits.json - do not edit\nvar CIRCUITS = " + json.dumps(out, separators=(",", ":"), ensure_ascii=False) + ";\n")
    print("circuits:", len(out), "missing:", missing, "bytes:", os.path.getsize(OUT), "points:", sum(len(v["pts"]) // 2 for v in out.values()))


main()
